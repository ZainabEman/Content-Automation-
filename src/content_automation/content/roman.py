"""Roman's identity references (config/design_directions.json `roman`).

Every image of Roman is generated by Higgsfield Soul 2.0 from his saved character (v6 R4; never
swapped for another provider, never replaced by a real photo). The approved real photos are
identity references only: the identity sheet at the person check puts a generated image beside
two of them, and the verdict is recorded with `ca job review --person pass|fail`.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps

from content_automation.content.directions import RomanRules

SHEET_HEIGHT = 900
_PROJECT_ROOT = Path(__file__).resolve().parents[3]
_FONT = _PROJECT_ROOT / "assets" / "fonts" / "Jost-Medium.ttf"


class RomanError(ValueError):
    """A Roman rule is broken: a missing approved photo."""


def approved_photos(rules: RomanRules, identity_dir: Path) -> list[Path]:
    """The approved real photos that exist: identity references for the person check only."""
    found = [identity_dir / name for name in rules.approved_photos
             if (identity_dir / name).is_file()]
    if not found:
        raise RomanError(f"none of the approved photos ({', '.join(rules.approved_photos)}) is "
                         f"in {identity_dir}: copy the identity set onto this machine")
    return found


def identity_sheet(generated: Path, photos: Sequence[Path], target: Path) -> Path:
    """The generated image beside approved real photos, one PNG for the person check."""
    tiles: list[tuple[str, Image.Image]] = []
    with Image.open(generated) as image:
        tiles.append(("GENERATED", ImageOps.contain(image.convert("RGB"),
                                                   (SHEET_HEIGHT, SHEET_HEIGHT))))
    for photo in photos:
        with Image.open(photo) as image:
            upright = ImageOps.exif_transpose(image).convert("RGB")
            tiles.append((f"REAL {photo.name}", ImageOps.contain(upright,
                                                                (SHEET_HEIGHT, SHEET_HEIGHT))))
    gap, label_h = 24, 64
    width = sum(tile.width for _, tile in tiles) + gap * (len(tiles) + 1)
    sheet = Image.new("RGB", (width, SHEET_HEIGHT + label_h + 2 * gap), (255, 255, 255))
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.truetype(str(_FONT), 34)
    x = gap
    for label, tile in tiles:
        sheet.paste(tile, (x, gap + label_h + (SHEET_HEIGHT - tile.height) // 2))
        draw.text((x + tile.width / 2, gap + label_h / 2), label, font=font, fill=(0, 75, 160),
                  anchor="mm")
        x += tile.width + gap
    target.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(target, format="PNG", optimize=True)
    return target


__all__ = ["RomanError", "approved_photos", "identity_sheet"]
