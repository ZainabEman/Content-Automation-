"""v6 (PRD R3.6): checks of a finished image, read from its pixels and its text.

`ca design check` (workflows/design_check.py) checks what the app drew from its render manifest;
these checks look at the image itself, so they also catch what an image model drew:

- the base colour: the median of the darkest 40% of the pixels must lie in the dark range sampled
  from the approved references (config/designer_prompts.json `checks.base`), never a flat bright
  blue or a light grey/white base;
- the text read from the image (OCR or the vision check, workflows/text_reader.py) against the
  intended German strings, exactly (umlauts, ß, punctuation): an intended string not found, and
  any stray text left over (layout coordinates, placeholders, slide numbers, an extra wordmark,
  fake or English words) fail;
- the logo: only the app's official file in its allowed corner, never on a Roman creative or a
  carousel slide other than the last; nothing read may overlap it;
- Roman: generated by Higgsfield Soul 2.0 only (a real photo is never the final image), no logo and
  no website.

Every error starts with its reason code in brackets ("[coordinates] ..."), so tests and reports can
name the reason. Free: the text is passed in (read once by the caller).
"""

from __future__ import annotations

import re
import unicodedata
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from typing import Any

from PIL import Image

from content_automation.content.german import check_text as german_check

Box = tuple[float, float, float, float]  # shares of the image: left, top, right, bottom

CODES = ("coordinates", "placeholder", "slide_number", "extra_logo", "stray_text",
         "text_mismatch", "not_german", "flat_blue", "light_base", "base_colour", "real_photo",
         "roman_logo", "roman_website", "carousel_logo", "logo_overlap", "logo_corner")
WORDMARK = ("BRANDED", "GENIUS")
WEBSITE = "brandedgenius.de"
_COORDINATES = re.compile(r"\b[xy]\s*[:=]?\s*\d{1,3}\s*[-–]\s*\d{1,3}\s*%|\b\d{1,3}\s*[-–]\s*"
                          r"\d{1,3}\s*%|\b(?:zone|box)\s*\d", re.IGNORECASE)
_PLACEHOLDER = re.compile(r"placeholder|lorem|ipsum|\b(?:CS|FB|FA|LI)-R?\d\b|\bTODO\b|"
                          r"\bAa\s+Bb\b|\bheadline\b|\bsubline\b", re.IGNORECASE)
_SLIDE_NUMBER = re.compile(r"^(?:0\d|\d{1,2}\s*/\s*\d{1,2}|\d{1,2}\s+(?:von|of)\s+\d{1,2})$",
                           re.IGNORECASE)
_EDGE_PUNCT = "\"'„“”‚‘’«»()[]"


@dataclass(frozen=True)
class ReadText:
    """One piece of text read from the image; box (shares) when the reader gives one."""

    text: str
    box: Box | None = None

    @classmethod
    def parse(cls, value: object) -> ReadText:
        if isinstance(value, dict):
            raw = value.get("box")
            box = tuple(float(v) for v in raw) if isinstance(raw, list) and len(raw) == 4 else None
            return cls(str(value.get("text", "")), box)  # type: ignore[arg-type]
        return cls(str(value))


@dataclass
class ImageFacts:
    """What an image is meant to be: from the job record, or a fixture's sidecar JSON."""

    category: str  # instagram_carousel | facebook_post | facebook_ad | linkedin_post
    roman: bool = False
    provider: str = ""  # openrouter | higgsfield_soul | template | photo (a real photo)
    last_slide: bool = True  # a carousel: this is its closing slide
    logo_box: Box | None = None  # where the app placed the official logo (shares)
    website: bool = False  # the app drew the website
    read: list[ReadText] | None = None  # None: the text was not read (the text checks skip)
    intended: list[str] = field(default_factory=list)  # the exact strings the image must show

    @classmethod
    def parse(cls, data: dict[str, Any]) -> ImageFacts:
        read = data.get("read")
        box = data.get("logoBox")
        return cls(category=str(data.get("category", "")), roman=bool(data.get("roman")),
                   provider=str(data.get("provider", "")),
                   last_slide=bool(data.get("lastSlide", True)),
                   logo_box=tuple(float(v) for v in box) if box else None,  # type: ignore[arg-type]
                   website=bool(data.get("website")),
                   read=[ReadText.parse(item) for item in read] if isinstance(read, list)
                   else None,
                   intended=[str(item) for item in data.get("intended") or []])


@dataclass
class TextMatch:
    missing: list[str] = field(default_factory=list)  # intended strings not found exactly
    leftover: list[str] = field(default_factory=list)  # words read that nobody intended

    @property
    def passed(self) -> bool:
        return not self.missing and not self.leftover


def normalise(text: str) -> str:
    """NFC, one space between words; characters, case and punctuation are kept (exact)."""
    return " ".join(unicodedata.normalize("NFC", text).replace("­", "").split())


def _words(text: str) -> list[str]:
    return normalise(text).split()


def _joined_words(read: Sequence[ReadText]) -> list[str]:
    """The words read, with a word hyphenated across two lines joined again ("Automati-" +
    "sierung"); a hyphen before a capital stays ("KI-" + "Agenten" -> "KI-Agenten")."""
    words: list[str] = []
    for item in read:
        line = _words(item.text)
        if words and line and words[-1].endswith("-") and len(words[-1]) > 1:
            words[-1] = (words[-1][:-1] if line[0][:1].islower() else words[-1]) + line.pop(0)
        words += line
    return words


def _same_word(read: str, intended: str) -> bool:
    """Spelling, umlauts and ß must match; edge punctuation and quote style do not, and a word
    the model set in capitals matches its capitalised form (ß -> SS in capitals)."""
    first, second = read.strip(_EDGE_PUNCT + ".,:;!?"), intended.strip(_EDGE_PUNCT + ".,:;!?")
    if first == second:
        return True
    return bool(first) and first.replace("ẞ", "SS").isupper() and (
        first.replace("ẞ", "SS") == second.upper())


def match_text(read: Sequence[ReadText], intended: Iterable[str],
               allowed: Iterable[str] = (), *, tolerant: bool = False) -> TextMatch:
    """Find every intended string, word for word and in order, in the text read; what is left
    is stray text. `allowed`: strings the app drew itself (the wordmark once, the website).
    tolerant (a build's own check): line breaks, hyphenation at a line end, edge punctuation
    and capitals are normalised; the letters themselves must match."""
    words = (_joined_words(read) if tolerant else
             [word for item in read for word in _words(item.text)])
    used = [False] * len(words)
    result = TextMatch()

    def same(found: list[str], target: list[str]) -> bool:
        if not tolerant:
            return found == target
        return all(_same_word(a, b) for a, b in zip(found, target, strict=True))

    def take(target: list[str]) -> bool:
        size = len(target)
        for start in range(len(words) - size + 1):
            if not any(used[start:start + size]) and same(words[start:start + size], target):
                for index in range(start, start + size):
                    used[index] = True
                return True
        return False

    for text in intended:
        target = _words(text)
        if target and not take(target):
            result.missing.append(normalise(text))
    for text in allowed:
        take(_words(text))
    result.leftover = [word for word, done in zip(words, used, strict=True) if not done]
    return result


def _overlap(first: Box, second: Box) -> bool:
    return first[0] < second[2] and second[0] < first[2] and first[1] < second[3] and (
        second[1] < first[3])


def _is_wordmark(text: str) -> bool:
    return text.strip(_EDGE_PUNCT + ".,:;!?-–").upper() in WORDMARK


def classify_leftover(words: Sequence[str], *, carousel: bool) -> list[str]:
    """Stray words read from the image, named by their likely cause."""
    errors: list[str] = []
    text = " ".join(words)
    if not text:
        return errors
    if _COORDINATES.search(text):
        found = [m.group(0) for m in _COORDINATES.finditer(text)]
        errors.append(f"[coordinates] layout coordinates printed in the image: {', '.join(found)}"
                      " (zone numbers reached the image model)")
        text = _COORDINATES.sub(" ", text)
    if _PLACEHOLDER.search(text):
        errors.append(f"[placeholder] placeholder or specimen text in the image: "
                      f"\"{_PLACEHOLDER.search(text).group(0)}\"")  # type: ignore[union-attr]
        text = _PLACEHOLDER.sub(" ", text)
    numbers = [word for word in text.split() if _SLIDE_NUMBER.match(word.strip(_EDGE_PUNCT))]
    if numbers:
        errors.append(f"[slide_number] a slide number or counter in the image: "
                      f"{', '.join(numbers)}" + (" (carousels have none)" if carousel else ""))
        text = " ".join(word for word in text.split() if word not in numbers)
    marks = [word for word in text.split() if _is_wordmark(word)]
    if marks:
        errors.append(f"[extra_logo] the wordmark is drawn again ({' '.join(marks)}): only the "
                      "app places the official logo file")
        text = " ".join(word for word in text.split() if not _is_wordmark(word))
    rest = [word for word in text.split() if any(ch.isalnum() for ch in word)]
    if rest:
        errors.append(f"[stray_text] text nobody intended: \"{' '.join(rest)[:120]}\" (fake, "
                      "garbled or extra text drawn by the model)")
    return errors


def base_colour(image: Image.Image) -> tuple[int, int, int]:
    """The base: the median colour of the darkest 40% of the pixels."""
    small = image.convert("RGB").resize((96, 96))
    pixels: list[tuple[int, int, int]] = sorted(
        small.getdata(), key=lambda p: p[0] * 299 + p[1] * 587 + p[2] * 114)
    dark = pixels[: max(1, len(pixels) * 40 // 100)]
    red, green, blue = (sorted(channel)[len(channel) // 2] for channel in zip(*dark, strict=True))
    return red, green, blue


def _shares(image: Image.Image) -> tuple[float, float, float]:
    """(median brightness, share of bright royal-blue fill pixels, share of warm light pixels)."""
    pixels = list(image.convert("RGB").resize((96, 96)).getdata())
    light = sorted((r * 299 + g * 587 + b * 114) / 1000 for r, g, b in pixels)
    blue = sum(1 for r, g, b in pixels if b > 150 and r < 60 and 40 < g < 150 and b - r > 110)
    warm = sum(1 for r, g, b in pixels if r > b + 15 and (r * 299 + g * 587 + b * 114) > 60_000)
    return light[len(light) // 2], blue / len(pixels), warm / len(pixels)


def check_base(image: Image.Image, category: str, rules: dict[str, Any]) -> list[str]:
    """The base lies in the dark range sampled from the approved references (navy, carousels
    black): never a bright-blue fill, a light base or a warm daylight photo. Thresholds in
    config/designer_prompts.json checks.base, calibrated on the references and the rejected
    sample (tests/fixtures/rejected/)."""
    red, green, blue = base_colour(image)
    hexed = f"#{red:02X}{green:02X}{blue:02X}"
    limit = int(rules.get("carouselMax" if category == "instagram_carousel" else "feedMax", 52))
    brightness = (red * 299 + green * 587 + blue * 114) / 1000
    median, blue_share, warm_share = _shares(image)
    errors: list[str] = []
    if (blue >= int(rules.get("brightBlueFrom", 110)) and blue - red >= 60) or (
            blue_share >= float(rules.get("blueShareFrom", 0.2))):
        errors.append(f"[flat_blue] a bright-blue fill covers {blue_share:.0%} of the image "
                      f"(base {hexed}); the approved base is near-black midnight navy, blue only "
                      "as glow, lines and accents")
    if brightness >= float(rules.get("lightFrom", 100)) or median >= float(
            rules.get("medianLightFrom", 90)):
        errors.append(f"[light_base] the image is light (base {hexed}, median brightness "
                      f"{median:.0f}); the approved base is near-black navy (carousels: black)")
    if errors:
        return errors
    if warm_share >= float(rules.get("warmShareFrom", 0.15)):
        return [f"[base_colour] a warm daylight photo ({warm_share:.0%} warm light pixels), not "
                "the dark navy look of the approved references"]
    if max(red, green, blue) > limit or red > blue + 4 or green > blue + 8:
        return [f"[base_colour] the base {hexed} is outside the dark navy range sampled from "
                f"the approved references (max channel {limit}, navy or black)"]
    return []


def check_image(image: Image.Image, facts: ImageFacts, rules: dict[str, Any],
                base: bool = True, warnings: list[str] | None = None) -> list[str]:
    """Every image-level error, each with its reason code (base=False: not the base colour,
    e.g. Roman's Higgsfield photo, checked by workflows/roman_check.py instead).

    warnings (a build's own check, not `ca design check` of a fixture): the text fails only for
    a wrong or missing intended string or a logo/wordmark; small glyphs inside the illustration
    ("AI" on a chip, short UI lines in a mockup), as in the approved references, and other stray
    words are only reported into `warnings`."""
    errors = check_base(image, facts.category, rules.get("base", {})) if base else []
    carousel = facts.category == "instagram_carousel"
    logo_allowed = not facts.roman and (not carousel or facts.last_slide)
    if facts.roman and facts.provider != "higgsfield_soul":
        errors.append("[real_photo] Roman's image is not from Higgsfield Soul 2.0 (his saved "
                      "character): a real photo is never the final image")
    if facts.logo_box is not None and not logo_allowed:
        errors.append("[roman_logo] a Roman creative carries no logo" if facts.roman else
                      "[carousel_logo] a carousel shows the logo only on its last slide")
    if facts.website and not logo_allowed:
        errors.append("[roman_website] a Roman creative carries no website" if facts.roman else
                      "[carousel_logo] a carousel shows the website only on its last slide")
    if facts.read is None:
        return errors
    read_all = " ".join(item.text for item in facts.read)
    if facts.roman and any(_is_wordmark(word) for word in read_all.split()):
        errors.append("[roman_logo] the Branded Genius wordmark is on a Roman creative")
    if WEBSITE in read_all.lower() and (facts.roman or not logo_allowed) and not facts.website:
        errors.append("[roman_website] the website is on a Roman creative" if facts.roman else
                      "[carousel_logo] the website is on a carousel slide other than the last")
    if carousel and not facts.last_slide and any(_is_wordmark(word)
                                                 for word in read_all.split()):
        errors.append("[carousel_logo] a logo on a carousel slide other than the last")
    if facts.logo_box is not None:
        overlapping = [item.text for item in facts.read if item.box is not None
                       and not all(_is_wordmark(word) for word in item.text.split())
                       and _overlap(item.box, facts.logo_box)]
        if overlapping:
            errors.append(f"[logo_overlap] text drawn over the logo: {', '.join(overlapping)}")
    allowed: list[str] = []
    if facts.logo_box is not None:  # the app's logo (a forbidden one is reported above)
        allowed.append(" ".join(WORDMARK))
    if facts.website:
        allowed.append(WEBSITE)
    lenient = warnings is not None
    matched = match_text(facts.read, facts.intended, allowed, tolerant=lenient)
    errors += [f"[text_mismatch] the intended text is not in the image exactly: \"{text}\""
               for text in matched.missing]
    leftover = classify_leftover(matched.leftover, carousel=carousel)
    language = [f"[not_german] {problem}" for problem in german_check(
        read_all, "image text").errors if "English" in problem or "englisch" in problem.lower()]
    if not lenient:
        return errors + leftover + language
    marks = [word for word in matched.leftover if WEBSITE in word.lower()]
    if marks:
        errors.append(f"[extra_logo] the model drew the website ({' '.join(marks)}): only the "
                      "app places the logo and the website")
    errors += [found for found in leftover if found.startswith("[extra_logo]")]
    assert warnings is not None
    warnings += [found for found in leftover + language if not found.startswith("[extra_logo]")]
    return errors


def codes(errors: Iterable[str]) -> set[str]:
    """The reason codes of a list of errors."""
    return {match.group(1) for error in errors if (match := re.match(r"\[(\w+)\]", error))}


