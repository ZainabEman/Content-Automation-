"""The `ca youtube` steps on the shared registry (BG IDs, approve/reject, audit) (PRD v5 R9).

plan → (approve/reject: `ca item approve|reject`) → research → check-sources (gate) → scripts
(3 briefs) → the agent writes 3 teleprompter files → bilingual → check → select style →
storyboard. Every step is free and local except check-sources, which opens the source URLs
(free, no cost; never run in tests). Nothing is generated by a paid model in `ca`.
"""

