DELIVERABLE = "youtube_longform"
BRIEFS_DIR = ".briefs"  # the writer's internal style briefs (English)


def _month_dates(month: str, count: int) -> list[date]:
    first = date.fromisoformat(f"{month}-01")
    return [first + timedelta(days=round(index * 28 / max(1, count)) + 1)
            for index in range(count)]


def plan_topics(conn: sqlite3.Connection, month: str, topics: list[str], *,
                root: Path | None = None, command: str | None = None) -> list[str]:
    """Up to topicsPerMonth YouTube items for the month (Proposed, own BG IDs), one folder
    each. Topics come from the agent's research (real incidents first); never invented here."""
    wanted = int(load_config()["topicsPerMonth"])
    existing = [item for item in list_items(conn) if item.kind == "youtube"
                and item.deliverable == DELIVERABLE and item.planned_date is not None
                and item.planned_date.isoformat().startswith(month)]
    lines = [f"YouTube {month}: {len(existing)} topic(s) already planned (target {wanted})."]
    room = max(0, wanted - len(existing))
    dates = _month_dates(month, wanted)[len(existing):]
    for title, day in list(zip(topics, dates, strict=False))[:room]:
        item = create_item(conn, kind="youtube", title=title, topic=title, platforms=["youtube"],
                           planned_date=day, deliverable=DELIVERABLE, command=command)
        set_design(conn, item.id, language="de", command=command)
        folder = topic_folder(month, item.id, title, root)
        write_package(folder, {"bgId": item.id, "month": month, "title": title,
                               "slug": slug(title), "status": "proposed",
                               "sourceCheck": None, "styles": {}, "selectedStyle": None})
        lines.append(f"{item.id} {day} {title} → {folder.as_posix()}")
    if len(topics) > room:
        lines.append(f"{len(topics) - room} topic(s) not added: the month already has {wanted}.")
    if room and len(topics) < room:
        lines.append(f"{room - len(topics)} slot(s) still open: research more real German "
                     "incidents (make-youtube) and add them with --topic.")
    lines.append("Next: approve or reject each topic (approve BG-x / reject BG-x <reason>); "
                 "then research BG-x.")
    return lines


def _approved(conn: sqlite3.Connection, bg_id: str) -> Item:
    item = get_item(conn, bg_id)
    if item.kind != "youtube":
        raise YoutubeError(f"{item.id} is a {item.kind}, not a YouTube topic")
    if item.idea_status != "approved":
        raise YoutubeError(f"{item.id} is {item.idea_status}: approve the topic first "
                           f"(uv run ca item approve {item.id})")
    return item


def research(conn: sqlite3.Connection, bg_id: str, *, root: Path | None = None) -> list[str]:
    """Write the research template (once), else check its structure (free)."""
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    data = read_package(folder)
    path = research_file(folder)
    if not path.exists():
        atomic_write_text(path, template(item.title, item.id, data["month"], data["slug"]))
        return [f"Research template: {path.as_posix()}",
                "Fill it from sources you opened (R9.3: German sources first, "
                "config/sources_de.json); then: uv run ca youtube check-sources " + item.id]
    problems = structure_problems(research_file_module.read(path))
    if problems:
        return [f"{path.as_posix()}: {len(problems)} problem(s):",
                *[f"- {problem}" for problem in problems]]
    return [f"{path.as_posix()}: complete. Next: uv run ca youtube check-sources {item.id}"]


def run_source_check(conn: sqlite3.Connection, bg_id: str, *, override: str | None = None,
                     root: Path | None = None, command: str | None = None) -> list[str]:
    """R9.5: check every URL, quotation and fact; write the results into the research file."""
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    data = read_package(folder)
    path = research_file(folder)
    if not path.exists():
        raise YoutubeError(f"{item.id}: no research file yet (uv run ca youtube research "
                           f"{item.id})")
    found = research_file_module.read(path)
    problems = structure_problems(found)
    if problems:
        raise YoutubeError(f"{path.name} is not complete: " + "; ".join(problems[:5]))
    report = check_sources(found)
    lines = list(report.lines)
    status = "passed" if report.passed else "failed"
    if not report.passed and override:
        status = "overridden"
        lines.append(f"OVERRIDE by Roman ({datetime.now(UTC):%Y-%m-%d}): {override}")
    text = path.read_text(encoding="utf-8")
    atomic_write_text(path, replace_verification(text, lines))
    data["sourceCheck"] = {"status": status, "problems": report.failures,
                           "humanChecks": report.human_checks,
                           "at": datetime.now(UTC).isoformat(timespec="seconds"),
                           **({"override": override} if status == "overridden" else {})}
    write_package(folder, data)
    append_event(conn, "decision" if status == "overridden" else "item_updated",
                 command=command, item_id=item.id,
                 actor="user" if status == "overridden" else "system",
                 details={"sourceCheck": status, "problems": len(report.failures),
                          **({"override": override} if override else {})})
    tail = ([f"Scripts are blocked until the problems are fixed or Roman overrides: "
             f'uv run ca youtube check-sources {item.id} --override "<reason>"']
            if status == "failed" else [f"Next: uv run ca youtube scripts {item.id}"])
    return [*lines, f"Written into {path.as_posix()} (VERIFICATION)", *tail]


def _gate(data: dict[str, Any], bg_id: str) -> None:
    check = data.get("sourceCheck") or {}
    if check.get("status") not in ("passed", "overridden"):
        raise YoutubeError(f"{bg_id}: the source check has not passed "
                           f"({check.get('status') or 'not run'}); fix the research or let "
                           "Roman override it (logged)")


def write_briefs(conn: sqlite3.Connection, bg_id: str, *, root: Path | None = None) -> list[str]:
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    data = read_package(folder)
    _gate(data, item.id)
    found = research_file_module.read(research_file(folder))
    lines = []
    briefs = folder / BRIEFS_DIR  # internal: kept out of the R9.11 style folders
    for key, style in styles().items():
        target = style_dir(folder, key)
        target.mkdir(parents=True, exist_ok=True)
        brief = briefs / f"{style.folder}.md"
        brief.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(brief, brief_text(style, item.title, found))
        lines.append(f"Style {key} {style.name}: write {(target / TELEPROMPTER).as_posix()} "
                     f"(brief: {brief.as_posix()})")
    return [*lines, f"Then: uv run ca youtube bilingual {item.id}"]


def make_bilingual(conn: sqlite3.Connection, bg_id: str, *,
                   root: Path | None = None) -> list[str]:
    """R9.9: script_DE-EN.txt from each teleprompter file (English kept where unchanged)."""
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    lines = []
    for key in styles():
        target = style_dir(folder, key)
        teleprompter = target / TELEPROMPTER
        if not teleprompter.exists():
            lines.append(f"Style {key}: no {TELEPROMPTER} yet")
            continue
        bilingual = target / BILINGUAL
        previous = bilingual.read_text(encoding="utf-8") if bilingual.exists() else None
        atomic_write_text(bilingual, bilingual_text(teleprompter.read_text(encoding="utf-8"),
                                                    previous))
        lines.append(f"Style {key}: {bilingual.as_posix()} (fill every English block)")
    return [*lines, f"Then: uv run ca youtube check {item.id}"]


def check_scripts(conn: sqlite3.Connection, bg_id: str, *,
                  root: Path | None = None) -> tuple[bool, list[str]]:
    """Every style: teleprompter rules, the bilingual identity, and the difference check."""
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    data = read_package(folder)
    texts: dict[str, str] = {}
    lines: list[str] = []
    ok = True
    for key in styles():
        target = style_dir(folder, key)
        teleprompter = target / TELEPROMPTER
        if not teleprompter.exists():
            lines.append(f"Style {key}: FAIL no {TELEPROMPTER}")
            ok = False
            continue
        text = teleprompter.read_text(encoding="utf-8")
        texts[key] = text
        errors, warnings = teleprompter_problems(text, key)
        bilingual = target / BILINGUAL
        errors += (bilingual_problems(text, bilingual.read_text(encoding="utf-8"))
                   if bilingual.exists() else [f"no {BILINGUAL}: uv run ca youtube bilingual"])
        ok = ok and not errors
        lines.append(f"Style {key}: {'PASS' if not errors else 'FAIL'}")
        lines += [f"  error: {error}" for error in errors]
        lines += [f"  warning: {warning}" for warning in warnings]
        data.setdefault("styles", {})[key] = {
            "teleprompter": (target / TELEPROMPTER).relative_to(folder).as_posix(),
            "bilingual": (target / BILINGUAL).relative_to(folder).as_posix(),
            "check": "passed" if not errors else "failed", "warnings": warnings}
    flags = similarity_flags(texts)
    lines += [f"Difference check: {flag}" for flag in flags] or (
        ["Difference check: the styles differ."] if len(texts) > 1 else [])
    write_package(folder, data)
    return ok, lines


def write_storyboards(conn: sqlite3.Connection, bg_id: str, *, root: Path | None = None,
                      command: str | None = None) -> list[str]:
    """R9.10: write an editing storyboard for every checked script style, without selecting one."""
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    data = read_package(folder)
    missing = [key for key, style in styles().items()
               if (data.get("styles") or {}).get(style.key, {}).get("check") != "passed"]
    if missing:
        raise YoutubeError(f"styles {', '.join(missing)} have not passed their check: "
                           f"uv run ca youtube check {item.id}")
    found = research_file_module.read(research_file(folder))
    boards: list[str] = []
    lines: list[str] = []
    for key, style in styles().items():
        target = style_dir(folder, key)
        board = folder / f"storyboard_{style.folder}.md"
        atomic_write_text(board, storyboard_text(
            style, item.title, item.id, (target / TELEPROMPTER).read_text(encoding="utf-8"),
            (target / BILINGUAL).read_text(encoding="utf-8"), found))
        boards.append(board.name)
        lines.append(f"Storyboard {key} {style.name}: {board.as_posix()} "
                     "(fill every <…>; the rest of the spec is PENDING).")
    data["storyboards"] = boards
    write_package(folder, data)
    append_event(conn, "item_updated", command=command, item_id=item.id,
                 actor="system", details={"storyboards": list(styles())})
    return [*lines, f"Created {len(boards)} storyboards; no production style was selected."]


def select_style(conn: sqlite3.Connection, bg_id: str, key: str, *, root: Path | None = None,
                 command: str | None = None) -> list[str]:
    """Mark the production choice and make sure every style has a storyboard."""
    item = _approved(conn, bg_id)
    folder = find_folder(item.id, root)
    data = read_package(folder)
    style = styles().get(key.upper())
    if style is None:
        raise YoutubeError(f'style "{key}": use A, B or C')
    state = (data.get("styles") or {}).get(style.key, {})
    if state.get("check") != "passed":
        raise YoutubeError(f"style {style.key} has not passed its check: uv run ca youtube "
                           f"check {item.id}")
    write_storyboards(conn, item.id, root=root, command=command)
    data = read_package(folder)
    data["selectedStyle"] = style.key
    data["storyboard"] = f"storyboard_{style.folder}.md"
    write_package(folder, data)
    set_design(conn, item.id, script_style=style.key, command=command)
    return [f"{item.id}: style {style.key} {style.name} selected (registry and package.json).",
            f"Created storyboards for every style: {', '.join(data['storyboards'])}.",
            "Production stays: Roman records, the editing agency edits (produce-video)."]


def status_lines(conn: sqlite3.Connection, month: str | None = None, *,
                 root: Path | None = None) -> list[str]:
    lines = []
    for item in list_items(conn):
        if item.kind != "youtube" or item.deliverable != DELIVERABLE:
            continue
        if month and not (item.planned_date and item.planned_date.isoformat().startswith(month)):
            continue
        try:
            data = read_package(find_folder(item.id, root))
        except YoutubeError:
            data = {}
        check = (data.get("sourceCheck") or {}).get("status", "not run")
        passed = [key for key, value in (data.get("styles") or {}).items()
                  if value.get("check") == "passed"]
        lines.append(f"{item.id} {item.planned_date or '—'} {item.idea_status:<9} sources "
                     f"{check:<10} styles passed {','.join(passed) or '-':<6} selected "
                     f"{data.get('selectedStyle') or '-'}  {item.title}")
    return lines or ["No YouTube topics yet: uv run ca youtube plan <YYYY-MM>"]


