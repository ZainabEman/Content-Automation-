"""Phase D step 6: Roman's identity rules (offline: drawn stand-in photos, no provider called).

Since 2026-10-20 Roman is made with Higgsfield Soul 2.0; the LoRA rules below stay tested for
the disabled RunPod/ComfyUI route, on the founder variants as they were (config/_archive)."""

import json
from pathlib import Path

import pytest
from PIL import Image

from content_automation.content.directions import Direction, Visual, load_directions
from content_automation.content.roman import (
    RomanError,
    approved_photos,
    check_strength,
    identity_sheet,
    prompt_problems,
    roman_prompt,
    text_side,
)

ARCHIVE = Path(__file__).resolve().parents[1] / "config/_archive/roman_lora_guidelines_v5.json"


def _lora_founder(direction_id: str) -> Direction:
    """The founder variant on the disabled LoRA route (its archived visual and layout)."""
    old = json.loads(ARCHIVE.read_text(encoding="utf-8"))["founderVariants"][direction_id]
    data = load_directions().get(direction_id).model_dump(by_alias=True, exclude_none=True)
    data.update(visual=old["visual"], provider=old["provider"], layouts=old["layouts"],
                pick="single")
    return Direction.model_validate(data)


def _photos(folder: Path, names: list[str]) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for name in names:
        Image.new("RGB", (120, 160), (90, 90, 90)).save(folder / name)


def test_every_pool_combination_passes_the_rules() -> None:
    catalog = load_directions()
    for direction_id in ("FB-R1", "FA-R1", "LI-R1"):
        direction = _lora_founder(direction_id)
        for name in direction.layouts:
            layout = direction.layouts[name]
            prompts = {roman_prompt(direction, layout, catalog.roman, seed=str(seed))
                       for seed in range(120)}
            assert len(prompts) > 10
            for prompt in prompts:
                assert prompt.startswith(catalog.roman.prefix) and prompt.endswith("no text")
    lora = _lora_founder("LI-R1")
    assert roman_prompt(lora, lora.layouts["post"], catalog.roman, seed="BG-4") == roman_prompt(
        lora, lora.layouts["post"], catalog.roman, seed="BG-4")


def test_every_roman_direction_is_higgsfield_never_the_lora() -> None:
    catalog = load_directions()
    roman = [d for d in catalog.directions if d.roman]
    assert [d.id for d in roman] == ["FB-R1", "FA-R1", "LI-R1"]  # one per category (R4.1)
    assert all(d.visual.subject == "roman_higgsfield" and d.provider == "higgsfield_soul"
               and set(d.layouts) == {"roman_right", "roman_left"} for d in roman)
    with pytest.raises(RomanError, match="does not use Roman's LoRA"):  # the route is off
        roman_prompt(catalog.get("LI-R1"), catalog.get("LI-R1").layouts["roman_right"],
                     catalog.roman, seed="x")
    with pytest.raises(ValueError, match="always generated by his LoRA"):
        Visual(subject="roman_real")
    with pytest.raises(RomanError, match="does not use Roman's LoRA"):
        roman_prompt(catalog.get("FB-1"), catalog.get("FB-1").layouts["post"], catalog.roman,
                     seed="x")


def test_blocked_props_and_missing_rules_are_refused() -> None:
    rules = load_directions().roman
    bad = f"{rules.prefix}, on a yacht at sunset, holding champagne"
    problems = prompt_problems(bad, rules)
    assert any("yacht" in p for p in problems) and any("champagne" in p for p in problems)
    assert any("alone" in p for p in problems) and any("no text" in p for p in problems)
    assert any("trigger" in p for p in prompt_problems("a man, no text", rules))
    assert not prompt_problems(f"{rules.prefix}, office, {rules.alone}, no text", rules)


def test_lora_strength_range() -> None:
    rules = load_directions().roman
    check_strength(0.9, rules)
    with pytest.raises(RomanError, match="outside"):
        check_strength(1.2, rules)


def test_approved_real_photos_are_identity_references_only(tmp_path: Path) -> None:
    rules = load_directions().roman
    _photos(tmp_path, ["1.jpg", "2.jpg", "4.jpg", "10.jpeg"])
    found = [path.name for path in approved_photos(rules, tmp_path)]
    assert found == ["2.jpg", "4.jpg"]  # 1.jpg is not approved, 10.jpeg looks AI-generated
    with pytest.raises(RomanError, match="none of the approved photos"):
        approved_photos(rules, tmp_path / "empty")


def test_text_side_follows_the_layout() -> None:
    catalog = load_directions()
    founder = _lora_founder("LI-R1")
    assert text_side(founder.layouts["post"]) == "on the left side of the frame"
    assert text_side(catalog.get("LI-R1").layouts["roman_left"]) == ("on the right side of "
                                                                    "the frame")


def test_identity_sheet_puts_the_image_beside_real_photos(tmp_path: Path) -> None:
    _photos(tmp_path / "set", ["2.jpg", "4.jpg"])
    generated = tmp_path / "raw.png"
    Image.new("RGB", (800, 1000), (10, 60, 140)).save(generated)
    sheet = identity_sheet(generated, [tmp_path / "set" / "2.jpg", tmp_path / "set" / "4.jpg"],
                           tmp_path / "job" / "identity_sheet_raw.png")
    with Image.open(sheet) as image:
        assert image.height > 900 and image.width > 3 * 600
